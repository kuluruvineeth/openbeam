function resolveLogoKey(name: string): string | undefined {
  const normalized = name.toLowerCase().trim();
  return (
    NAME_MAP[normalized] ??
    Object.entries(NAME_MAP).find(([key]) => normalized.includes(key))?.[1]
  );
}

function McpClientLogo({ id, size = 36 }: { id: string; size?: number }) {
  const def = LOGOS[id];
  if (!def) {
    return null;
  }
  return def.render({ size });
}

function resolveLogo(
  name: string
): ((props: LogoProps) => React.ReactElement) | undefined {
  const key = resolveLogoKey(name);
  if (!(key && LOGOS[key])) {
    return;
  }
  const resolved = LOGOS[key];
  if (!resolved) {
    return;
  }
  return ({ size = 36 }: LogoProps) => resolved.render({ size });
}

